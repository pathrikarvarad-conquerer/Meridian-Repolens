import {
  RepositoryMetadata,
  ProjectOverviewData,
  SetupDoctorData,
  RecommendedIssue
} from '../types';

export function generateOnboardingMarkdown(
  metadata: RepositoryMetadata,
  overview: ProjectOverviewData,
  setupDoctor: SetupDoctorData,
  issues: RecommendedIssue[]
): string {
  const shortSha = metadata.commitSha ? metadata.commitSha.substring(0, 7) : 'head';
  const timestamp = new Date().toISOString().split('T')[0];

  const prereqList = setupDoctor.prerequisites.length > 0
    ? setupDoctor.prerequisites.map(p => `- **${p.name}**: \`${p.versionRequirement}\` *(Source: ${p.detectedIn})*`).join('\n')
    : '- No strict prerequisites detected.';

  const installCmd = setupDoctor.installCommands[0]?.command || 'npm install';
  const testCmd = setupDoctor.testCommands[0]?.command || 'npm test';

  const dirList = overview.keyDirectories.map(d => `- **\`${d.path}/\`**: ${d.role} (${d.fileCount} files, ${d.primaryLanguage})`).join('\n');

  const readingList = overview.readingPath.map(r => `${r.step}. **\`${r.path}\`** — ${r.title}\n   - *Purpose*: ${r.purpose}\n   - *Key Concepts*: ${r.keyConcepts.join(', ')}\n   - *Est. Time*: ~${r.estimatedMinutes} mins`).join('\n\n');

  const issuesList = issues.map(iss => `### #${iss.number}: [${iss.title}](${iss.url})
- **Difficulty**: ${iss.difficulty}
- **Labels**: ${iss.labels.map(l => `\`${l}\``).join(', ')}
- **Why this issue**: ${iss.matchReason}
- **Relevant Files**: ${iss.relevantFiles.map(f => `\`${f.path}\``).join(', ')}
- **Relevant Tests**: ${iss.relevantTests.length > 0 ? iss.relevantTests.map(t => `\`${t.path}\``).join(', ') : 'None specified'}
${iss.uncertaintyNotes ? `- **Notes**: ${iss.uncertaintyNotes}` : ''}`).join('\n\n');

  return `# Onboarding Guide: ${metadata.fullName}

> Generated by **RepoLens** on ${timestamp} for commit \`${shortSha}\` (${metadata.defaultBranch}).
> **Notice:** This guide is generated via static repository analysis. Commands and prerequisites should be reviewed before execution.

---

## Table of Contents
1. [Project Overview](#project-overview)
2. [Prerequisites & System Setup](#prerequisites--system-setup)
3. [Building & Testing](#building--testing)
4. [Important Directories](#important-directories)
5. [Recommended Reading Path](#recommended-reading-path)
6. [First Contribution: Recommended Issues](#first-contribution-recommended-issues)
7. [Analysis Limitations & Disclaimers](#analysis-limitations--disclaimers)

---

## 1. Project Overview

${overview.purpose}

- **Primary Language:** ${metadata.primaryLanguage}
- **License:** ${metadata.license || 'Not specified'}
- **Repository URL:** [${metadata.url}](${metadata.url})
- **Target Audience:** ${overview.targetAudience}

### Core Workflows
${overview.coreWorkflows.map(w => `- ${w}`).join('\n')}

---

## 2. Prerequisites & System Setup

Ensure you have the following installed on your development workstation:

${prereqList}

### Installation Steps

Clone the repository and install dependencies:

\`\`\`bash
git clone ${metadata.url}.git
cd ${metadata.name}
${installCmd}
\`\`\`

---

## 3. Building & Testing

### Running Tests
Execute the documented test command:

\`\`\`bash
${testCmd}
\`\`\`

> **Setup Doctor Disclaimer:** RepoLens detected this command in \`${setupDoctor.testCommands[0]?.evidence?.sourcePath || 'manifest'}\`. Static analysis does not execute scripts locally.

---

## 4. Important Directories

Understanding the directory hierarchy helps orient your file navigation:

${dirList}

---

## 5. Recommended Reading Path

To understand the core mechanisms without getting lost in boilerplate:

${readingList}

---

## 6. First Contribution: Recommended Issues

RepoLens selected these open issues based on file locality, test coverage, and modular boundaries:

${issuesList}

---

## 7. Analysis Limitations & Disclaimers

- **Static Analysis Only:** RepoLens did not execute arbitrary code or test runners in a live sandbox.
- **Evidence Traceability:** All findings are referenced back to specific files and line numbers in commit \`${shortSha}\`.
- **Secrets & Credentials:** No credentials or environment secrets are included in this export.

*Generated with [RepoLens](https://github.com)*
`;
}

/**
 * Downloads a string as a file in the browser
 */
export function downloadMarkdownFile(content: string, filename: string = 'ONBOARDING.md') {
  const blob = new Blob([content], { type: 'text/markdown;charset=utf-8' });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.download = filename;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}
